CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,

    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,

    phone_number VARCHAR(20),
    phone_visible_to_organizers BOOLEAN NOT NULL DEFAULT FALSE,

    avatar_url VARCHAR(500),
    avatar_updated_at TIMESTAMPTZ,

    role VARCHAR(20) NOT NULL DEFAULT 'USER',

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_users_role
        CHECK (role IN ('USER', 'ORGANIZER', 'ADMIN')),

    CONSTRAINT chk_users_phone_consent
        CHECK (
            phone_visible_to_organizers = FALSE
            OR phone_number IS NOT NULL
        )
);

CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    name VARCHAR(100) NOT NULL UNIQUE,
    description TEXT,

    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    title VARCHAR(200) NOT NULL,
    description TEXT NOT NULL,

    city VARCHAR(100) NOT NULL,
    address VARCHAR(255) NOT NULL,

    latitude NUMERIC(9,6) NOT NULL,
    longitude NUMERIC(9,6) NOT NULL,

    start_at TIMESTAMPTZ NOT NULL,
    end_at TIMESTAMPTZ NOT NULL,

    capacity INTEGER NOT NULL,

    status VARCHAR(30) NOT NULL DEFAULT 'DRAFT',

    organizer_id BIGINT NOT NULL,
    category_id BIGINT NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_events_organizer
        FOREIGN KEY (organizer_id)
        REFERENCES users(id),

    CONSTRAINT fk_events_category
        FOREIGN KEY (category_id)
        REFERENCES categories(id),

    CONSTRAINT chk_events_capacity
        CHECK (capacity > 0),

    CONSTRAINT chk_events_dates
        CHECK (end_at > start_at),

    CONSTRAINT chk_events_latitude
        CHECK (latitude BETWEEN -90 AND 90),

    CONSTRAINT chk_events_longitude
        CHECK (longitude BETWEEN -180 AND 180),

    CONSTRAINT chk_events_status
        CHECK (
            status IN (
                'DRAFT',
                'PENDING_MODERATION',
                'PUBLISHED',
                'REJECTED',
                'CANCELLED',
                'COMPLETED'
            )
        )
);

CREATE TABLE registrations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id BIGINT NOT NULL,
    event_id BIGINT NOT NULL,

    status VARCHAR(20) NOT NULL DEFAULT 'CONFIRMED',

    registered_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_registrations_user
        FOREIGN KEY (user_id)
        REFERENCES users(id),

    CONSTRAINT fk_registrations_event
        FOREIGN KEY (event_id)
        REFERENCES events(id),

    CONSTRAINT chk_registrations_status
        CHECK (status IN ('CONFIRMED', 'CANCELLED'))
);

-- One active registration per user and event.
-- A cancelled registration does not prevent registering again.
CREATE UNIQUE INDEX uq_registrations_active
    ON registrations(user_id, event_id)
    WHERE status = 'CONFIRMED';

CREATE TABLE favorites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id BIGINT NOT NULL,
    event_id BIGINT NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_favorites_user
        FOREIGN KEY (user_id)
        REFERENCES users(id),

    CONSTRAINT fk_favorites_event
        FOREIGN KEY (event_id)
        REFERENCES events(id),

    CONSTRAINT uq_favorites_user_event
        UNIQUE (user_id, event_id)
);

CREATE TABLE event_images (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    event_id BIGINT NOT NULL,

    image_url VARCHAR(500) NOT NULL,
    is_primary BOOLEAN NOT NULL DEFAULT FALSE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_event_images_event
        FOREIGN KEY (event_id)
        REFERENCES events(id)
);

CREATE TABLE event_moderation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    event_id BIGINT NOT NULL,
    actor_id BIGINT NOT NULL,

    action VARCHAR(20) NOT NULL,
    comment TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_event_moderation_event
        FOREIGN KEY (event_id)
        REFERENCES events(id),

    CONSTRAINT fk_event_moderation_actor
        FOREIGN KEY (actor_id)
        REFERENCES users(id),

    CONSTRAINT chk_event_moderation_action
        CHECK (
            action IN (
                'SUBMITTED',
                'APPROVED',
                'REJECTED'
            )
        )
);

-- Only one primary image per event.
CREATE UNIQUE INDEX uq_event_images_primary
    ON event_images(event_id)
    WHERE is_primary = TRUE;

-- Event discovery and filtering
CREATE INDEX idx_events_city
    ON events(city);

CREATE INDEX idx_events_start_at
    ON events(start_at);

CREATE INDEX idx_events_category
    ON events(category_id);

CREATE INDEX idx_events_organizer
    ON events(organizer_id);

CREATE INDEX idx_events_status
    ON events(status);

-- Registration lookup
CREATE INDEX idx_registrations_event
    ON registrations(event_id);

-- Favorite lookup
CREATE INDEX idx_favorites_user
    ON favorites(user_id);

-- Moderation history lookup
CREATE INDEX idx_event_moderation_event
    ON event_moderation(event_id);

-- Event image lookup
CREATE INDEX idx_event_images_event
    ON event_images(event_id);

